"""Deterministic, non-writing renderer for the supported Ren'Py template subset."""

from __future__ import annotations

import re
from collections.abc import Iterable

from rentr.domain import TranslationKind, TranslationUnit, build_source_hash

_LANGUAGE_PATTERN = re.compile(r"^[a-z]+(?:_[a-z]+)*$")
_IDENTIFIER_PATTERN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_DIALOGUE_UNIT_ID = re.compile(r"^(?P<block_id>[A-Za-z0-9_]+?)(?::(?P<occurrence>[1-9][0-9]*))?$")
_LABELLED_ID = re.compile(r"^(?P<label>.+)_[0-9a-fA-F]{8}$")
_PREVIEW_HEADER = "# Generated by RenTR — deterministic dry-run preview."


class TemplateRenderError(ValueError):
    """Raised when inventory cannot be rendered without losing supported semantics."""


def _quote_renpy_text(text: str) -> str:
    escaped: list[str] = []
    escapes = {
        "\\": "\\\\",
        '"': '\\"',
        "\n": "\\n",
        "\r": "\\r",
        "\t": "\\t",
    }
    for character in text:
        if character in escapes:
            escaped.append(escapes[character])
        elif ord(character) < 32:
            raise TemplateRenderError(f"Desteklenmeyen kontrol karakteri: U+{ord(character):04X}")
        else:
            escaped.append(character)
    return f'"{"".join(escaped)}"'


def _dialogue_block_id(unit: TranslationUnit) -> str:
    match = _DIALOGUE_UNIT_ID.fullmatch(unit.unit_id)
    if match is None:
        raise TemplateRenderError(f"Geçersiz diyalog kimliği: {unit.unit_id}")
    if match.group("occurrence") is not None:
        raise TemplateRenderError(
            f"Bir blokta birden fazla kaynak renderer kapsamı dışında: {unit.unit_id}"
        )

    block_id = match.group("block_id")
    label_match = _LABELLED_ID.fullmatch(block_id)
    derived_label = label_match.group("label") if label_match else None
    if unit.label != derived_label:
        raise TemplateRenderError(f"Diyalog kimliği ve label uyuşmuyor: {unit.unit_id}")
    return block_id


def _say_statement(speaker: str | None, text: str) -> str:
    if speaker is not None and _IDENTIFIER_PATTERN.fullmatch(speaker) is None:
        raise TemplateRenderError(f"Geçersiz konuşmacı kimliği: {speaker}")
    prefix = f"{speaker} " if speaker is not None else ""
    return f"{prefix}{_quote_renpy_text(text)}"


def _render_dialogue(unit: TranslationUnit, *, language: str) -> str:
    block_id = _dialogue_block_id(unit)
    source = _say_statement(unit.speaker, unit.source_text)
    if any(not segment for segment in unit.translated_segments):
        raise TemplateRenderError(f"Boş hedef segmenti desteklenmiyor: {unit.unit_id}")
    targets = unit.translated_segments or ("",)
    target_lines = [f"    {_say_statement(unit.speaker, text)}" for text in targets]
    return "\n".join(
        (
            f"translate {language} {block_id}:",
            "",
            f"    # {source}",
            *target_lines,
        )
    )


def _render_string_group(
    units: tuple[TranslationUnit, ...],
    *,
    language: str,
) -> str:
    lines = [f"translate {language} strings:", ""]
    for index, unit in enumerate(units):
        if unit.speaker is not None or unit.label is not None:
            raise TemplateRenderError(
                f"string birimi konuşmacı veya label içeremez: {unit.unit_id}"
            )
        if len(unit.translated_segments) > 1:
            raise TemplateRenderError(f"string hedefi tek segment olmalı: {unit.unit_id}")
        if unit.translated_segments and not unit.translated_segments[0]:
            raise TemplateRenderError(f"Boş hedef segmenti desteklenmiyor: {unit.unit_id}")
        target = unit.translated_segments[0] if unit.translated_segments else ""
        lines.extend(
            (
                f"    old {_quote_renpy_text(unit.source_text)}",
                f"    new {_quote_renpy_text(target)}",
            )
        )
        if index < len(units) - 1:
            lines.append("")
    return "\n".join(lines)


def render_template(
    units: Iterable[TranslationUnit],
    *,
    language: str = "turkish",
) -> str:
    """Render canonical Ren'Py text in memory without touching any files."""
    inventory = tuple(units)
    if not inventory:
        raise TemplateRenderError("boş envanter render edilemez")
    if _LANGUAGE_PATTERN.fullmatch(language) is None:
        raise TemplateRenderError(
            "Dil adı yalnız küçük ASCII harfler ve kelimeler arası alt çizgi içerebilir"
        )

    blocks: list[str] = []
    seen_dialogue_ids: set[str] = set()
    string_occurrences: dict[str, int] = {}
    index = 0
    while index < len(inventory):
        unit = inventory[index]
        if unit.kind is TranslationKind.STRING:
            group_end = index + 1
            while (
                group_end < len(inventory) and inventory[group_end].kind is TranslationKind.STRING
            ):
                group_end += 1
            for string_unit in inventory[index:group_end]:
                occurrence = string_occurrences.get(string_unit.source_text, 0) + 1
                string_occurrences[string_unit.source_text] = occurrence
                expected_id = (
                    f"strings:{build_source_hash(string_unit.source_text)[:16]}:{occurrence}"
                )
                if string_unit.unit_id != expected_id:
                    raise TemplateRenderError(
                        f"string kimliği kanonik kaynak kimliğiyle uyuşmuyor: {string_unit.unit_id}"
                    )
            blocks.append(
                _render_string_group(
                    inventory[index:group_end],
                    language=language,
                )
            )
            index = group_end
            continue

        block_id = _dialogue_block_id(unit)
        if block_id in seen_dialogue_ids:
            raise TemplateRenderError(f"yinelenen diyalog kimliği: {block_id}")
        seen_dialogue_ids.add(block_id)
        blocks.append(_render_dialogue(unit, language=language))
        index += 1

    return f"{_PREVIEW_HEADER}\n\n" + "\n\n".join(blocks) + "\n"
